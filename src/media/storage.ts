import path from 'path'

/**
 * Где физически лежат загруженные файлы (Roadmap **CR-04**).
 *
 * ## Что было сломано
 * У `Media` стоял `upload: true` без `staticDir`, и ни одного `@payloadcms/storage-*` в
 * зависимостях. Payload в таком случае резолвит каталог загрузок от рабочего каталога процесса,
 * а systemd-юнит указывает `WorkingDirectory=/opt/sealife/current` — симлинк, который деплой
 * перекидывает на свежий каталог `releases/<sha>`, залитый `rsync --delete`, после чего релизы
 * старше пятого удаляются `rm -rf`. То есть загруженные картинки лежали ВНУТРИ релиза и
 * исчезали на следующем деплое: каждая обложка отдавала бы 404.
 *
 * Локально это работает идеально — каталог никто не подменяет, — поэтому поломка проявилась бы
 * только после того, как оба сайта наполнены контентом. Ровно тот класс дефекта, который дешевле
 * закрыть до наполнения.
 *
 * ## Решение
 * Каталог задаётся ЯВНО и абсолютным путём:
 *  - прод: `MEDIA_DIR=/opt/sealife/shared/media` — вне `releases/`, деплой его не трогает;
 *  - дев/CI: по умолчанию `<репозиторий>/media` (в `.gitignore`).
 *
 * Внешнее объектное хранилище (S3/R2) сознательно НЕ вводится: инвариант data-residency требует
 * держать данные в EU/EEA, а бокс и так в EU — добавлять облачную зависимость ради задачи
 * «не удаляй каталог при деплое» дороже, чем один env.
 */

/**
 * Ровно та часть окружения, которая здесь нужна: сузили, чтобы тест не подделывал весь ProcessEnv.
 * Индексная сигнатура нужна, чтобы настоящий `process.env` (у него в проекте свой типизированный
 * вид) оставался присваиваемым.
 */
export type MediaEnv = { MEDIA_DIR?: string; [key: string]: string | undefined }

/** Абсолютный путь к каталогу загрузок. `repoRoot` — корень репозитория (для дев-дефолта). */
export function mediaStaticDir(repoRoot: string, env: MediaEnv = process.env): string {
  const configured = env.MEDIA_DIR?.trim()
  if (configured) {
    // Относительный путь резолвился бы от cwd — то есть ровно от подменяемого симлинка,
    // от которого мы и уходим. Такой конфиг лучше отвергнуть громко.
    if (!path.isAbsolute(configured)) {
      throw new Error(
        `MEDIA_DIR должен быть абсолютным путём (получено: "${configured}"). ` +
          'Относительный путь резолвится от рабочего каталога процесса, а в проде это симлинк ' +
          'на каталог релиза — загрузки исчезнут при следующем деплое (CR-04).',
      )
    }
    return configured
  }
  return path.resolve(repoRoot, 'media')
}

/**
 * Похоже ли, что каталог загрузок эфемерный — то есть лежит внутри каталога релиза и будет
 * снесён следующим деплоем. Эвристика по пути, не обращение к ФС: нужна ровно чтобы деплой без
 * `MEDIA_DIR` не проходил молча.
 */
export function isEphemeralMediaDir(dir: string, releasesRoot = '/opt/sealife/releases'): boolean {
  const normalized = dir.split(path.sep).join('/')
  return normalized.startsWith(`${releasesRoot}/`) || normalized.includes('/releases/')
}
