/**
 * Alt-текст обложки под выключенным locale-fallback (**CR-04** × **CR-01**).
 *
 * `media.alt` локализован и обязателен — но обязателен ПРИ ЗАПИСИ локали, а не «во всех локалях
 * сразу». После CR-01 фолбэк выключен, поэтому картинка, у которой alt заполнен только на
 * исходной локали, на другой приходит с пустым alt. Гейт перевода это не ловит: `media` — своя
 * коллекция со своими строками локалей, и полностью переведённая статья может нести
 * непереведённый alt.
 *
 * Правило по WCAG 1.1.1 зависит от роли картинки, а не от наличия текста:
 *  - обложка-**декорация** (карточка списка, hero статьи, где смысл несёт заголовок рядом) —
 *    пустой `alt=""` КОРРЕКТЕН: скринридер её пропустит, и это лучше, чем прочитать имя файла;
 *  - картинка, которая и ЕСТЬ содержание (детальная страница мема) — пустой alt это потеря
 *    контента. Туда передаём запасной текст (заголовок документа): он уже прошёл гейт перевода,
 *    значит гарантированно на языке страницы.
 */
export function coverAlt(
  image: { alt?: string | null } | null | undefined,
  fallbackText?: string | null,
): string {
  const alt = image?.alt?.trim()
  if (alt) return alt
  return fallbackText?.trim() || ''
}
