import type { Locale } from '@/i18n/config'
import type { SpeciesFactsRow } from '@/app/(frontend)/_components/content/getSpecies'

/**
 * Bento-хаб главной sealife (Roadmap **M1-T05**) — чистая логика.
 *
 * ## Иерархия объявлена, а не выведена из контента
 * Порядок слотов — буквально порядок приоритета из `docs/DESIGN_BRIEF.md` §6a, и он ЗАШИТ здесь, а
 * не зависит от того, что нашлось в базе. Это и есть «фикс-иерархия» из формулировки задачи: размер
 * плитки задаётся её областью в `grid-template-areas` (см. `.bento` в globals.css), а порядок DOM
 * совпадает с визуальным — то есть клавиатура и скринридер идут по той же иерархии, что и глаз.
 * `grid-auto-flow: dense` и masonry запрещены §16 именно поэтому: они молча поднимают
 * низкоприоритетную плитку вверх.
 *
 * ## Плитка не исчезает
 * Пустой слот рендерит честное пустое состояние в СВОЕЙ области, а не пропадает. Иначе сетка даёт
 * дыры и «зажатые слева» карточки, которые §16 запрещает прямым текстом. Сегодня это режим по
 * умолчанию, а не край: сиды пишут `content` и `species` черновиками (BIO-16 — публикация есть
 * человеческое действие, инвариант №1), поэтому из шести слотов наполнен ровно один — игры.
 *
 * ## Чего здесь принципиально нет
 * Ни одного обращения к `@/mock/sample`. У главной нет `noindex` и она стоит первой записью в
 * sitemap, то есть mock-данные на ней обходят СРАЗУ оба механизма CR-09. Раздел на выдуманных
 * данных получает состояние `soon` и ноль запросов — см. `tileState`.
 */

/** Слоты в порядке приоритета §6a. Порядок = порядок DOM = визуальный порядок. */
export const BENTO_SLOTS = ['fact', 'quiz', 'meme', 'game', 'news', 'species'] as const
export type BentoSlot = (typeof BENTO_SLOTS)[number]

/**
 * Состояние плитки.
 *  - `filled` — есть реальные опубликованные и переведённые данные;
 *  - `empty` — данных нет; показываем честное пустое с приглашением в раздел (§8);
 *  - `soon` — раздел ещё на выдуманных данных (`mockBacked`), поэтому данных не берём ВООБЩЕ.
 */
export type TileState = 'filled' | 'empty' | 'soon'

/**
 * `soon` перебивает наличие данных: пока раздел `mockBacked`, плитка не имеет права ничего
 * показывать, даже если что-то нашлось. Флаг снимается вместе с переездом раздела на Payload
 * (quizzes → M1-T10), и та же плитка сама станет `filled`.
 */
export function tileState(hasData: boolean, mockBacked?: boolean): TileState {
  if (mockBacked) return 'soon'
  return hasData ? 'filled' : 'empty'
}

/**
 * Обложка для плитки — ТОЛЬКО реально загруженная картинка.
 *
 * Декоративный `PlaceholderMedia` в bento не годится по двум причинам, и вторая жёстче первой:
 *  1. Пустая картинка-заглушка становится самым крупным элементом главной, ничего не сообщая;
 *  2. Её тинт чередуется по seed и включает `bg-surface-warm` (sandbank) — а §6a резервирует
 *     тёплую пару sandbank + buoy-dark за переходом на sealrescue. Это единственный аварийный
 *     сигнал главной, и декору его отдавать нельзя. Проверено живьём: плитка игры без обложки
 *     выезжала именно тёплой.
 *
 * Поэтому плитка без настоящей картинки остаётся текстовой.
 */
export function realCover<T extends { url?: string | null }>(
  image: T | number | null | undefined,
): T | null {
  if (!image || typeof image !== 'object') return null
  return image.url ? image : null
}

export type DailyFact = { fact: string; name: string; href: string }

/**
 * Плоский пул фактов всех видов для «факта дня».
 *
 * ⚠️ Полевой случай CR-01: сам массив `facts` НЕ локализован — локализован только `facts.text`.
 * Значит у вида с переведённым `name` (документ прошёл гейт `translatedWhere`) отдельные факты
 * могут быть ещё не переведены и приходить пустыми. Пустая строка в пуле обнулила бы «факт дня»
 * для всей локали, поэтому непереведённые факты отсеиваем здесь — на гейт документа полагаться
 * нельзя, он работает на другом уровне.
 *
 * Пул собирается по ВСЕМ видам, а не по странице каталога: `pickOfDay` берёт `день % длина`, и
 * пул из одной страницы превратил бы «факт дня» в «факт первой страницы» (эту ошибку уже
 * поймал CR-07).
 */
export function factPool(rows: SpeciesFactsRow[], locale: Locale): DailyFact[] {
  return rows.flatMap((row) =>
    (row.facts ?? [])
      .filter((f) => f.text?.trim())
      .map((f) => ({
        fact: f.text,
        name: row.name,
        href: `/${locale}/species/${row.slug}`,
      })),
  )
}
