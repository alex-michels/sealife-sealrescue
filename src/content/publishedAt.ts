/**
 * Дата публикации материала (Roadmap **CR-05**).
 *
 * ## Что было сломано
 * Поля даты публикации в `Content` не было вовсе, поэтому читателю показывался `updatedAt`, и по
 * нему же сортировались лента главной и все списки. Через три недели наполнения это значит:
 * правка опечатки в мартовской статье поднимает её на первое место главной и передатирует перед
 * читателем. Для новостей, которые `CLAUDE.md` считает journalistisch-redaktionell под §18 MStV,
 * «дата = когда я последний раз трогал» — хуже, чем косметика.
 *
 * ## Правила
 * 1. Штамп ставится в момент ПЕРВОЙ публикации и больше не двигается. Переопубликовать материал
 *    после снятия с публикации — не значит «выпустить заново»: у читателя и у поисковика уже есть
 *    дата, и менять её задним числом нельзя.
 * 2. Черновику дата не нужна: пока материал не вышел, «даты выхода» не существует. Проставлять её
 *    заранее означало бы обещать публикацию, которой может не быть.
 * 3. Значение, выставленное человеком вручную, НЕ перетирается. Редактор может поставить реальную
 *    дату выхода (перенос старого материала, отложенная публикация) — автоматика уступает.
 *
 * ## Почему не локализовано
 * Дата публикации — факт о материале, а не о языке. Английский оригинал и русский перевод — один
 * материал, вышедший один раз; показывать читателю разные даты выхода одного текста значит
 * сообщать, что это два разных материала. (Дату появления ПЕРЕВОДА при необходимости несёт
 * `localeStatus[].translatedAt` — другое утверждение, см. CR-15.)
 */

export type PublishedAtInput = {
  _status?: string | null
  publishedAt?: string | null
}

/**
 * Значение `publishedAt` после записи, или `undefined` — «не трогать».
 *
 * @param incoming данные записи (`data` в beforeChange)
 * @param existing прежнее состояние документа (`originalDoc`), если это обновление
 * @param now      момент записи; передаётся явно, чтобы правило было чистым и тестируемым
 */
export function nextPublishedAt(
  incoming: PublishedAtInput,
  existing: PublishedAtInput | null | undefined,
  now: string,
): string | undefined {
  // Что окажется в поле ПОСЛЕ этой записи. Ключевая тонкость — различать «поле не пришло в
  // partial-update» (`undefined` → берём прежнее) и «поле пришло пустым» (`null` → его очищают).
  const effective =
    incoming.publishedAt !== undefined ? incoming.publishedAt : existing?.publishedAt

  // Дата есть и остаётся — не двигаем (правила 1 и 3).
  if (effective) return undefined

  // Статус тоже берём из входящих, а на partial-update — из прежнего состояния: иначе правка
  // одного поля у опубликованного материала выглядела бы как «статус не задан» и штамп не встал бы.
  const status = incoming._status !== undefined ? incoming._status : existing?._status
  if (status !== 'published') return undefined

  // Опубликованный материал без даты выхода существовать не должен — в том числе если её только что
  // очистили руками. Иначе он уйдёт в начало списков: Postgres при `-publishedAt` ставит NULL первым.
  return now
}
