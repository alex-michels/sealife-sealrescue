// SR-21: deterministic delivery packing; original generated artwork stays versioned.
// Run from any directory: node public/games/seal-run-v1/tools/pack-art.mjs
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { FAUNA, faunaFile } from '../core/fauna.js'

const assets = new URL('../assets/', import.meta.url)
const atlases = {}
for (const id of [...Object.keys(FAUNA), 'polar_bear', 'leopard_seal']) {
  const frames = []
  for (let i = 0; i < 4; i++) {
    const file = FAUNA[id] ? faunaFile(id, i) : id.replaceAll('_', '-') + '-v3-' + i + '.webp'
    const input = await readFile(new URL(file, assets))
    const { data, info } = await sharp(input)
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true })
    let left = info.width,
      top = info.height,
      right = 0,
      bottom = 0
    for (let y = 0; y < info.height; y++)
      for (let x = 0; x < info.width; x++) {
        if (data[(y * info.width + x) * 4 + 3] === 0) continue
        left = Math.min(left, x)
        top = Math.min(top, y)
        right = Math.max(right, x)
        bottom = Math.max(bottom, y)
      }
    const rect = { left, top, width: right - left + 1, height: bottom - top + 1 }
    const crop = await sharp(input)
      .extract(rect)
      .extend({ top: 2, bottom: 2, left: 2, right: 2, extendWith: 'copy' })
      .png()
      .toBuffer()
    frames.push({ rect, crop, file, width: info.width, height: info.height })
  }
  const cellW = Math.max(...frames.map((f) => f.rect.width)) + 4
  const cellH = Math.max(...frames.map((f) => f.rect.height)) + 4
  const packed = await sharp({
    create: { width: cellW * 2, height: cellH * 2, channels: 4, background: '#00000000' },
  })
    .composite(
      frames.map((f, i) => ({
        input: f.crop,
        left: (i % 2) * cellW,
        top: Math.floor(i / 2) * cellH,
      })),
    )
    .webp({ quality: 90, alphaQuality: 100, smartSubsample: true })
    .toBuffer()
  const file = id.replaceAll('_', '-') + '-atlas-v6.webp'
  await writeFile(new URL(file, assets), packed)
  atlases[id] = {
    file,
    frames: Object.fromEntries(
      frames.map((f, i) => [
        id + '_' + i,
        {
          frame: {
            x: (i % 2) * cellW + 2,
            y: Math.floor(i / 2) * cellH + 2,
            w: f.rect.width,
            h: f.rect.height,
          },
          rotated: false,
          trimmed: true,
          spriteSourceSize: { x: f.rect.left, y: f.rect.top, w: f.rect.width, h: f.rect.height },
          sourceSize: { w: f.width, h: f.height },
        },
      ]),
    ),
    meta: {
      size: { w: cellW * 2, h: cellH * 2 },
      sources: frames.map((f) => f.file),
      extrusion: 2,
    },
  }
}
await writeFile(
  new URL('../render/atlas-data.js', import.meta.url),
  '// Generated by tools/pack-art.mjs. Do not edit frame coordinates.\nexport const ATLASES = ' +
    JSON.stringify(atlases, null, 2) +
    '\n',
)
for (const biome of ['coastal', 'atlantis', 'tropical', 'arctic', 'antarctic']) {
  // Native 3:1 panorama at the game's 540px logical height, without 1.34x oversampling.
  await sharp(fileURLToPath(new URL(biome + '-panorama-v2.webp', assets)))
    .resize(1620, 540)
    .webp({ quality: 86 })
    .toFile(fileURLToPath(new URL(biome + '-panorama-mobile-v6.webp', assets)))
}
console.log('Packed 10 four-frame atlases with 2px extrusion and 5 mobile panoramas.')
